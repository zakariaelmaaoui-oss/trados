// Postgres persistence layer.
//  * Production (Vercel): DATABASE_URL → Neon/any Postgres via `pg`.
//  * Local / tests: embedded Postgres (PGlite) stored in DATA_DIR, or in memory.
// Exposes a tiny async API: get / all / run / tx, with `?` placeholders.
