/** `?` → `$1, $2 …` (none of our SQL contains a literal question mark). */
function toPg(sql) {
  let i = 0;
  return sql.replace(/\?/g, () => `$${++i}`);
}

function wrap(query) {
  const q = async (sql, params) => query(toPg(sql), params.map((p) => (p === undefined ? null : p)));
  return {
    get: async (sql, ...p) => (await q(sql, p)).rows[0],
    all: async (sql, ...p) => (await q(sql, p)).rows,
    run: async (sql, ...p) => { const r = await q(sql, p); return { changes: r.rowCount ?? r.affectedRows ?? 0, rows: r.rows }; },
  };
}

const INT8 = 20, NUMERIC = 1700;

export async function openDb({ url = process.env.DATABASE_URL, dir } = {}) {
  let db;
  if (url) {
    pgPkg.types.setTypeParser(INT8, (v) => Number(v));
    pgPkg.types.setTypeParser(NUMERIC, (v) => Number(v));
    const pool = new pgPkg.Pool({ connectionString: url, max: 3, ssl: /localhost|127\.0\.0\.1/.test(url) ? false : { rejectUnauthorized: true } });
    const base = wrap((sql, params) => pool.query(sql, params));
    db = {
      ...base, kind: 'postgres',
      exec: (sql) => pool.query(sql),
      tx: async (fn) => {
        const client = await pool.connect();
        try {
          await client.query('BEGIN');
          const r = await fn(wrap((sql, params) => client.query(sql, params)));
          await client.query('COMMIT');
          return r;
        } catch (e) { await client.query('ROLLBACK').catch(() => {}); throw e; } finally { client.release(); }
      },
      close: () => pool.end(),
    };
  } else {
    const { PGlite } = await import('@electric-sql/pglite');
    if (dir) fs.mkdirSync(dir, { recursive: true });
    const pg = new PGlite(dir || undefined, { parsers: { [INT8]: (v) => Number(v), [NUMERIC]: (v) => Number(v) } });
    await pg.waitReady;
    db = {
      ...wrap((sql, params) => pg.query(sql, params)), kind: 'pglite',
      exec: (sql) => pg.exec(sql),
      tx: (fn) => pg.transaction((t) => fn(wrap((sql, params) => t.query(sql, params)))),
      close: () => pg.close(),
    };
  }
  await db.exec(SCHEMA);
  return db;
}

export const tx = (db, fn) => db.tx(fn);

export async function kvGet(db, key) {
  const r = await db.get('SELECT value FROM app_kv WHERE key = ?', key);
  return r ? r.value : null;
}
export async function kvSet(db, key, value) {
  await db.run('INSERT INTO app_kv(key,value) VALUES(?,?) ON CONFLICT(key) DO UPDATE SET value=excluded.value', key, value);
}
